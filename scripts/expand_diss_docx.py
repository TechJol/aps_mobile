def find_paragraph_index(document: Document, prefix: str) -> int:
    for index, paragraph in enumerate(document.paragraphs):
        if paragraph.text.strip().startswith(prefix):
            return index
    raise ValueError(f"Paragraph starting with {prefix!r} was not found")


def paragraph_before(target, text: str = "", style: str | None = None):
    paragraph = target.insert_paragraph_before(text)
    if style:
        paragraph.style = style
    return paragraph


def table_before(target, rows: list[list[str]]) -> None:
    table = target._parent.add_table(rows=len(rows), cols=len(rows[0]), width=Inches(6.3))
    try:
        table.style = "Table Grid"
    except KeyError:
        pass
    for row_index, row in enumerate(rows):
        for col_index, value in enumerate(row):
            table.cell(row_index, col_index).text = str(value)
    target._element.addprevious(table._element)


def picture_before(target, image_path: Path, width_inches: float = 6.2) -> None:
    paragraph = paragraph_before(target)
    paragraph.add_run().add_picture(str(image_path), width=Inches(width_inches))


def append_heading(document: Document, text: str, level: int = 1) -> None:
    document.add_heading(text, level=level)


def append_table(document: Document, rows: list[list[str]]) -> None:
    widths = [max(len(str(row[col_index])) for row in rows) for col_index in range(len(rows[0]))]
    for row_index, row in enumerate(rows):
        values = [str(value).replace("\n", " ") for value in row]
        line = " | ".join(value.ljust(widths[index]) for index, value in enumerate(values))
        document.add_paragraph(line)
        if row_index == 0:
            document.add_paragraph("-+-".join("-" * width for width in widths))


def append_code(document: Document, title: str, lines: list[str]) -> None:
    document.add_paragraph(title)
    for line in lines:
        paragraph = document.add_paragraph(line.rstrip())
        try:
            paragraph.style = "No Spacing"
        except KeyError:
            pass


def append_code_file(document: Document, title: str, path: Path, max_lines: int = 140) -> None:
    document.add_paragraph(title)
    document.add_paragraph(f"Файл: {path.as_posix()}")
    if not path.exists():
        document.add_paragraph("Файл не найден.")
        return
    lines = path.read_text(encoding="utf-8").splitlines()[:max_lines]
    for index, line in enumerate(lines, start=1):
        paragraph = document.add_paragraph(f"{index:03d}: {line.rstrip()}")
        try:
            paragraph.style = "No Spacing"
        except KeyError:
            pass


def format_float(value: object, digits: int = 4) -> str:
    try:
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


